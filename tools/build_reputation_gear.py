"""Builds Mentor's ReputationGear.lua from Wowhead WoW Forever quartermaster pages (qm/*.txt lines:
npc|name|zone^x^y|factionId|react alliance,horde|item:reqLevel:wowheadStanding:copper;...)."""
import glob

OUTPUT = "/home/claude/mentor/ReputationGear.lua"
# Wowhead standing 0-7 (Hated..Exalted) -> the game's reaction 1-8.
WOWHEAD_TO_GAME_STANDING = 1
# Faction names we know from the vendor titles (the game names the rest).
FACTION_NAMES = {369: "Gadgetzan", 2798: "Darkspear Raiders"}

def faction_sides(react_text):
    alliance, horde = (react_text.split(",") + ["null"])[:2]
    usable = lambda value: value not in ("null", "") and int(value) >= 0
    return ("A" if usable(alliance) else "") + ("H" if usable(horde) else "")

def q(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'

vendors, items = {}, {}
for path in sorted(glob.glob("qm/*.txt")):
    for line in open(path):
        line = line.strip()
        if not line:
            continue
        npc_id, name, where, faction_ids, react, item_text = line.split("|")
        zone_name, x, y = where.split("^")
        faction_id = int(faction_ids.split(",")[0])
        vendors[int(npc_id)] = (name, faction_id, faction_sides(react), zone_name, float(x), float(y))
        for item_entry in item_text.split(";"):
            item_id, required_level, standing, copper = (int(n) for n in item_entry.split(":"))
            items[item_id] = (int(npc_id), required_level, standing + WOWHEAD_TO_GAME_STANDING, copper)

lines = ["--------------------------------------------------------------------------------",
         "-- Mentor - ReputationGear.lua (generated by tools/build_reputation_gear.py)",
         "-- Gear the new WoW Forever quartermasters sell for gold once you have enough",
         "-- reputation with their faction. From the quartermasters' Wowhead pages (Nov 2026).",
         "--   Mentor.REPUTATION_VENDORS[npc id] = { \"name\", faction id, \"faction name\" or false,",
         "--       \"A\"/\"H\"/\"AH\" (who can buy), \"zone\", x, y }",
         "--   Mentor.REPUTATION_GEAR[item id] = { npc id, required level,",
         "--       standing needed (5 Friendly, 6 Honored, 7 Revered, 8 Exalted), price in copper }",
         "--------------------------------------------------------------------------------",
         "", "local _, Mentor = ...", "", "Mentor.REPUTATION_VENDORS = {"]
for npc_id in sorted(vendors):
    name, faction_id, sides, zone_name, x, y = vendors[npc_id]
    faction_name = q(FACTION_NAMES[faction_id]) if faction_id in FACTION_NAMES else "false"
    lines.append(f"    [{npc_id}] = {{ {q(name)}, {faction_id}, {faction_name}, \"{sides}\", {q(zone_name)}, {x}, {y} }},")
lines += ["}", "", "Mentor.REPUTATION_GEAR = {"]
for item_id in sorted(items):
    npc_id, required_level, standing, copper = items[item_id]
    lines.append(f"    [{item_id}] = {{ {npc_id}, {required_level}, {standing}, {copper} }},")
lines.append("}")
open(OUTPUT, "w").write("\n".join(lines) + "\n")
print(len(vendors), "vendors,", len(items), "items")
