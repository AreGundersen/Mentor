"""Builds EnchantRecipes.lua: every Enchanting recipe that enchants an item
slot in WoW Forever, from AllTheThings' WoW Forever profession database
(.contrib/.db/forever/profession db/enchanting.lua in ATTWoWAddon/AllTheThings).

Only the released sections are used (the file's "UNKNOWN" and "UNRELEASED
CONTENT" parts are commented out there and skipped here). What each enchant
gives is read in game from the spell description, so only spell id, formula
item, slot and name are stored.

Usage: python3 tools/build_enchant_recipes.py <enchanting.lua> <output EnchantRecipes.lua>
"""
import re
import sys

SOURCE_PATH, OUTPUT_PATH = sys.argv[1], sys.argv[2]

source_text = open(SOURCE_PATH, encoding="utf-8").read()
released_text = source_text.split("--- UNKNOWN ---")[0]

# i(formulaItemId, spellId);  -- Enchant <Slot> - <Name>   (formulaItemId 0 = trainer)
recipe_pattern = re.compile(r"^i\((\d+),\s*(\d+)\);\s*--\s*Enchant (.+?) - (.+?)\s*$", re.M)
recipes = []
for formula_item_id, spell_id, slot_name, enchant_name in recipe_pattern.findall(released_text):
    recipes.append((int(spell_id), int(formula_item_id), slot_name, enchant_name))
recipes.sort(key=lambda recipe: (recipe[2], recipe[3]))


def lua_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


lines = [
    "--------------------------------------------------------------------------------",
    "-- Mentor - EnchantRecipes.lua (generated by tools/build_enchant_recipes.py from",
    "-- AllTheThings' WoW Forever enchanting database - do not edit by hand)",
    "-- Every released enchant for an item slot in WoW Forever:",
    "--   { spellId, formulaItemId (0 = taught by trainers), slot, name }",
    "--------------------------------------------------------------------------------",
    "",
    "local _, Mentor = ...",
    "",
    "Mentor.ENCHANT_RECIPES = {",
]
for spell_id, formula_item_id, slot_name, enchant_name in recipes:
    lines.append(f"    {{ {spell_id}, {formula_item_id}, {lua_string(slot_name)}, {lua_string(enchant_name)} }},")
lines.append("}")
open(OUTPUT_PATH, "w", encoding="utf-8").write("\n".join(lines) + "\n")
print(f"{len(recipes)} enchants -> {OUTPUT_PATH}")
