"""Builds DungeonQuestStarts.lua: the quests that belong to each classic
dungeon and who starts them (NPC and zone), from Questie's classic database
(v9.5.2). A quest belongs to a dungeon when Questie files it under the
dungeon's area (zoneOrSort). Mentor's Journey tab and dungeon tip use it to
say which quests to pick up before going in.

Usage: python3 tools/build_dungeon_quest_starts.py <folder with classicQuestDB.lua,
classicNpcDB.lua, classicItemDB.lua and lookupZones.lua> <output DungeonQuestStarts.lua>
"""
import re
import sys

import lupa

QUESTIE_FOLDER, OUTPUT_PATH = sys.argv[1], sys.argv[2]

QUEST_NAME, QUEST_STARTED_BY, QUEST_REQUIRED_LEVEL, QUEST_LEVEL = 1, 2, 4, 5
QUEST_REQUIRED_RACES, QUEST_REQUIRED_CLASSES, QUEST_ZONE_OR_SORT = 6, 7, 17
QUEST_SPECIAL_FLAGS = 24
NPC_NAME, NPC_ZONE = 1, 9
ITEM_NAME = 1

ALLIANCE_RACES = 1 | 4 | 8 | 64       # Human, Dwarf, Night Elf, Gnome
HORDE_RACES = 2 | 16 | 32 | 128       # Orc, Undead, Tauren, Troll

# Mentor's dungeon names (Journey.lua) -> the area ids Questie files their quests under.
DUNGEON_AREAS = {
    "Ragefire Chasm": [2437],
    "Wailing Caverns": [718],
    "The Deadmines": [1581],
    "Shadowfang Keep": [209],
    "Blackfathom Deeps": [719],
    "The Stockade": [717],
    "Razorfen Kraul": [491],
    "Gnomeregan": [721],
    "Scarlet Monastery Graveyard": [796],
    "Scarlet Monastery Library": [796],
    "Scarlet Monastery Armory": [796],
    "Scarlet Monastery Cathedral": [796],
    "Razorfen Downs": [722],
    "Uldaman": [1337],
    "Zul'Farrak": [1176, 978],
    "Maraudon": [2100],
    "The Temple of Atal'Hakkar": [1477, 1417],
    "Blackrock Depths": [1584],
    "Dire Maul": [2557],
    "Lower Blackrock Spire": [1583],
    "Upper Blackrock Spire": [1583],
    "Stratholme": [2017],
    "Scholomance": [2057],
}


def load_questie_table(path, marker):
    text = open(path, encoding="utf-8").read()
    start = text.index(marker) + len(marker)
    return lupa.LuaRuntime().execute(text[start:text.index("]]", start)])


quests = load_questie_table(f"{QUESTIE_FOLDER}/classicQuestDB.lua", "QuestieDB.questData = [[")
npcs = load_questie_table(f"{QUESTIE_FOLDER}/classicNpcDB.lua", "QuestieDB.npcData = [[")
items = load_questie_table(f"{QUESTIE_FOLDER}/classicItemDB.lua", "QuestieDB.itemData = [[")
zone_source = open(f"{QUESTIE_FOLDER}/lookupZones.lua", encoding="utf-8").read()
zone_names = {}
for zone_id, name in re.findall(r"\[(\d+)\]\s*=\s*\"([^\"]+)\"", zone_source):
    zone_names.setdefault(int(zone_id), name)

quests_by_area = {}
for quest_id, quest in quests.items():
    area_id = quest[QUEST_ZONE_OR_SORT]
    if area_id and area_id > 0:
        quests_by_area.setdefault(area_id, []).append((int(quest_id), quest))


def describe_start(quest):
    """'NPC name', 'zone' of who starts the quest (or the item that starts it)."""
    started_by = quest[QUEST_STARTED_BY]
    if not started_by:
        return None, None
    creatures = list(started_by[1].values()) if started_by[1] else []
    for creature_id in creatures:
        npc = npcs[creature_id]
        if npc:
            return npc[NPC_NAME], zone_names.get(npc[NPC_ZONE], "")
    start_items = list(started_by[3].values()) if started_by[3] else []
    for item_id in start_items:
        item = items[item_id]
        if item:
            return "item: " + item[ITEM_NAME], ""
    return None, None


def lua_string(text):
    return '"' + (text or "").replace("\\", "\\\\").replace('"', '\\"') + '"'


lines = [
    "--------------------------------------------------------------------------------",
    "-- Mentor - DungeonQuestStarts.lua (generated by tools/build_dungeon_quest_starts.py",
    "-- from Questie's classic database - do not edit by hand)",
    "-- Quests for each classic dungeon and who starts them:",
    "--   [dungeon] = { { quest id, \"name\", side (1 Alliance, 2 Horde, 3 both),",
    "--                   level you can take it at, \"starts with\", \"zone\" }, ... }",
    "-- Class-only and repeatable quests are left out.",
    "--------------------------------------------------------------------------------",
    "",
    "local _, Mentor = ...",
    "",
    "Mentor.DUNGEON_QUEST_STARTS = {",
]
total_quests = 0
for dungeon_name, area_ids in DUNGEON_AREAS.items():
    dungeon_quests = []
    for area_id in area_ids:
        for quest_id, quest in quests_by_area.get(area_id, []):
            if quest[QUEST_REQUIRED_CLASSES] or (quest[QUEST_SPECIAL_FLAGS] or 0) & 1:
                continue
            starter_name, starter_zone = describe_start(quest)
            if not starter_name:
                continue
            races = quest[QUEST_REQUIRED_RACES] or 0
            side = 3
            if races and not races & HORDE_RACES:
                side = 1
            elif races and not races & ALLIANCE_RACES:
                side = 2
            dungeon_quests.append((quest_id, quest[QUEST_NAME], side, quest[QUEST_REQUIRED_LEVEL] or 1,
                                   starter_name, starter_zone))
    dungeon_quests.sort(key=lambda entry: (entry[3], entry[1]))
    total_quests += len(dungeon_quests)
    lines.append(f"    [{lua_string(dungeon_name)}] = {{")
    for quest_id, name, side, level, starter_name, starter_zone in dungeon_quests:
        lines.append(f"        {{ {quest_id}, {lua_string(name)}, {side}, {level}, {lua_string(starter_name)}, {lua_string(starter_zone)} }},")
    lines.append("    },")
lines.append("}")
open(OUTPUT_PATH, "w", encoding="utf-8").write("\n".join(lines) + "\n")
print(f"{total_quests} quests in {len(DUNGEON_AREAS)} dungeons -> {OUTPUT_PATH}")
