"""Builds QuestTurnIns.lua: for each classic quest, the zone where it is turned
in and the NPC who takes it, from Questie's classic database (v9.5.2).

Mentor uses it to say "3 quests ready to turn in here" when you are in that
zone. Quests turned in at an object (a chest, a sign) only get the zone of the
object when known; WoW Forever's own new quests are not in this database, so
Mentor falls back to the quest log's zone header for them.

Usage: python3 tools/build_quest_turn_ins.py <folder with classicQuestDB.lua,
classicNpcDB.lua and lookupZones.lua> <output QuestTurnIns.lua>
"""
import re
import sys

import lupa

QUESTIE_FOLDER = sys.argv[1]
OUTPUT_PATH = sys.argv[2]

# Field numbers in Questie's tables (see questKeys / npcKeys in the files).
QUEST_NAME, QUEST_FINISHED_BY, QUEST_ZONE_OR_SORT = 1, 3, 17
NPC_NAME, NPC_ZONE = 1, 9


def load_questie_table(path, marker):
    """Questie keeps each database as Lua source in a long string; run it."""
    text = open(path, encoding="utf-8").read()
    start = text.index(marker) + len(marker)
    inner_source = text[start:text.index("]]", start)]
    return lupa.LuaRuntime().execute(inner_source)


quests = load_questie_table(f"{QUESTIE_FOLDER}/classicQuestDB.lua", "QuestieDB.questData = [[")
npcs = load_questie_table(f"{QUESTIE_FOLDER}/classicNpcDB.lua", "QuestieDB.npcData = [[")
zone_source = open(f"{QUESTIE_FOLDER}/lookupZones.lua", encoding="utf-8").read()
zone_names = {int(zone_id): name for zone_id, name in re.findall(r"\[(\d+)\]\s*=\s*\"([^\"]+)\"", zone_source)}

zone_list, zone_index_by_name = [], {}
npc_list, npc_index_by_name = [], {}


def index_of(name, name_list, index_by_name):
    if name not in index_by_name:
        name_list.append(name)
        index_by_name[name] = len(name_list)
    return index_by_name[name]


turn_ins = {}
for quest_id, quest in quests.items():
    finished_by = quest[QUEST_FINISHED_BY]
    creature_ids = list(finished_by[1].values()) if finished_by and finished_by[1] else []
    zone_name, npc_name = None, None
    for creature_id in creature_ids:
        npc = npcs[creature_id]
        if npc and zone_names.get(npc[NPC_ZONE]):
            zone_name, npc_name = zone_names[npc[NPC_ZONE]], npc[NPC_NAME]
            break
    if not zone_name:
        # Turned in at an object: the quest's own zone is the best guess.
        zone_or_sort = quest[QUEST_ZONE_OR_SORT]
        if zone_or_sort and zone_or_sort > 0 and zone_names.get(zone_or_sort):
            zone_name = zone_names[zone_or_sort]
    if zone_name:
        zone_index = index_of(zone_name, zone_list, zone_index_by_name)
        npc_index = index_of(npc_name, npc_list, npc_index_by_name) if npc_name else 0
        turn_ins[int(quest_id)] = zone_index * 65536 + npc_index


def lua_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


lines = [
    "--------------------------------------------------------------------------------",
    "-- Mentor - QuestTurnIns.lua (generated by tools/build_quest_turn_ins.py from",
    "-- Questie's classic database - do not edit by hand)",
    "-- Where each classic quest is turned in: zone and NPC.",
    "--   TURN_IN_ZONES[n] / TURN_IN_NPCS[n]: the names",
    "--   QUEST_TURN_INS[questId] = zoneNumber * 65536 + npcNumber (npcNumber 0 = an object)",
    "--------------------------------------------------------------------------------",
    "",
    "local _, Mentor = ...",
    "",
    "Mentor.TURN_IN_ZONES = { " + ", ".join(lua_string(name) for name in zone_list) + " }",
    "",
    "Mentor.TURN_IN_NPCS = {",
]
for start in range(0, len(npc_list), 8):
    lines.append("    " + ", ".join(lua_string(name) for name in npc_list[start:start + 8]) + ",")
lines += ["}", "", "Mentor.QUEST_TURN_INS = {"]
quest_ids = sorted(turn_ins)
for start in range(0, len(quest_ids), 10):
    lines.append("    " + " ".join(f"[{quest_id}]={turn_ins[quest_id]}," for quest_id in quest_ids[start:start + 10]))
lines.append("}")
open(OUTPUT_PATH, "w", encoding="utf-8").write("\n".join(lines) + "\n")
print(f"{len(turn_ins)} quests, {len(zone_list)} zones, {len(npc_list)} NPCs -> {OUTPUT_PATH}")
